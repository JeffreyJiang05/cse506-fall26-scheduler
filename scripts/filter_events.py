#!/usr/bin/env python3
"""
filter_events.py - Filter scheduler event logs by CPU cores.

Filters event logs generated by grid_sched to extract events related to a
specified set of CPU cores. This includes:
  - Tasks dispatched, cancelled, or preempted on the core(s).
  - Tasks enqueued to the core(s), or enqueued after previous execution on the core(s).
  - Tasks migrated to or from the core(s) during work stealing (src_cpu, dst_cpu, target_cpu).

Usage:
  python3 filter_events.py <input_log> <target_output_log> <core1> [core2 ...]
  python3 filter_events.py <input_log> -o <target_output_log> <core1> [core2 ...]
  python3 filter_events.py -i <input_log> -o <target_output_log> -c <cores...>
"""

import sys
import os
import re
import argparse
from typing import Set, List, Tuple, Dict


# Matches any CPU field in scheduler event lines:
#   - cpu=X (in new_dsq, prev_dsq, dispatch, cancel, preempt)
#   - src_cpu=X (migration source: moved FROM this CPU)
#   - dst_cpu=X (migration destination: moved TO this CPU)
#   - target_cpu=X (migration DSQ CPU)
CPU_PATTERN = re.compile(r'\b(?:cpu|src_cpu|dst_cpu|target_cpu)\s*=\s*(\d+)')
EVENT_TYPE_PATTERN = re.compile(r'EVENT\s*\[\d+\]:\s*([A-Z_]+)')


def parse_core_token(token: str) -> Set[int]:
    """
    Parse a core specification token which can be:
      - a single integer: "3" -> {3}
      - a comma-separated list: "0,1,2" -> {0, 1, 2}
      - a range: "0-3" -> {0, 1, 2, 3}
      - a combination: "0-2,4,6-7" -> {0, 1, 2, 4, 6, 7}
    """
    cores = set()
    parts = token.split(',')
    for part in parts:
        part = part.strip()
        if not part:
            continue
        if '-' in part:
            bounds = part.split('-')
            if len(bounds) == 2 and bounds[0].strip().isdigit() and bounds[1].strip().isdigit():
                start = int(bounds[0].strip())
                end = int(bounds[1].strip())
                if start > end:
                    start, end = end, start
                cores.update(range(start, end + 1))
            else:
                raise ValueError(f"Invalid range specification: '{part}'")
        elif part.isdigit():
            cores.add(int(part))
        else:
            raise ValueError(f"Invalid core number: '{part}'")
    return cores


def parse_cpu_cores(items: List[str]) -> Set[int]:
    """Parse a list of core argument tokens into a set of integers."""
    all_cores = set()
    for item in items:
        all_cores.update(parse_core_token(item))
    return all_cores


def is_core_token(token: str) -> bool:
    """Check if a string token looks like a core or core range (e.g. '0', '0,1', '0-3')."""
    try:
        parse_core_token(token)
        return True
    except ValueError:
        return False


def filter_log(
    input_path: str,
    output_path: str,
    target_cores: Set[int],
    include_global: bool = False
) -> Tuple[int, int, Dict[str, int]]:
    """
    Read input_path, filter events matching target_cores, and write to output_path.
    Returns (total_lines, matched_lines, event_type_counts).
    """
    total_lines = 0
    matched_lines = 0
    event_counts: Dict[str, int] = {}

    with open(input_path, 'r', encoding='utf-8', errors='replace') as infile, \
         open(output_path, 'w', encoding='utf-8') as outfile:
        for line in infile:
            total_lines += 1

            # Extract any CPU references on this line
            line_cpus = {int(c) for c in CPU_PATTERN.findall(line)}

            is_match = bool(line_cpus & target_cores)

            if not is_match and include_global:
                # Check for global lifecycle events with no CPU fields (e.g. SCHED_START, SCHED_END)
                if not line_cpus and ('SCHED_START' in line or 'SCHED_END' in line):
                    is_match = True

            if is_match:
                outfile.write(line)
                matched_lines += 1

                # Track event type statistics
                m = EVENT_TYPE_PATTERN.search(line)
                ev_type = m.group(1) if m else "OTHER"
                event_counts[ev_type] = event_counts.get(ev_type, 0) + 1

    return total_lines, matched_lines, event_counts


def parse_args():
    parser = argparse.ArgumentParser(
        description="Filter scheduler event logs for events related to a specific set of CPU cores.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Using positional arguments (target log file followed by CPU cores):
  python3 scripts/filter_events.py logs/events.log logs/filtered.log 0 1 2

  # Using -o / --target option:
  python3 scripts/filter_events.py logs/events.log -o logs/core0.log 0

  # Comma-separated or range format for cores:
  python3 scripts/filter_events.py logs/events.log logs/cores_0_to_3.log 0-3
  python3 scripts/filter_events.py logs/events.log -o logs/out.log 0,2,4-6

  # Including global scheduler lifecycle events (SCHED_START, SCHED_END):
  python3 scripts/filter_events.py logs/events.log logs/filtered.log 0 1 --include-global
"""
    )

    parser.add_argument(
        "-i", "--input", "--source", dest="input_log", default=None,
        help="Path to the input scheduler log file."
    )
    parser.add_argument(
        "-o", "--output", "--target", dest="target_log", default=None,
        help="Path to the target output log file for filtered events."
    )
    parser.add_argument(
        "-c", "--cores", "--cpus", dest="cores_opt", nargs="*", default=None,
        help="List of CPU core(s) to filter for (e.g., 0 1 2 or 0-3,5)."
    )
    parser.add_argument(
        "--include-global", action="store_true", default=False,
        help="Include global lifecycle events with no associated core (SCHED_START, SCHED_END)."
    )
    parser.add_argument(
        "positional_args", nargs="*",
        help="Positional arguments: <input_log> [target_log] <core1> [core2 ...]"
    )

    args = parser.parse_intermixed_args()

    input_log = args.input_log
    target_log = args.target_log
    raw_cores = list(args.cores_opt) if args.cores_opt else []
    pos_args = list(args.positional_args)

    # Resolve positional arguments
    # If input_log was not provided via -i/--input:
    if input_log is None:
        if not pos_args:
            parser.error("Missing input log file. Specify it as the first argument or via -i/--input.")
        input_log = pos_args.pop(0)

    # If target_log was not provided via -o/--output/--target:
    if target_log is None:
        if not pos_args:
            parser.error("Missing target output log file. Specify it as the second argument or via -o/--target.")
        # Check if the next positional argument is an output file or a core
        if not is_core_token(pos_args[0]):
            target_log = pos_args.pop(0)
        else:
            parser.error("Missing target output log file before CPU cores. Specify it via -o/--target or as the second argument.")

    # Any remaining positional arguments are CPU cores
    raw_cores.extend(pos_args)

    if not raw_cores:
        parser.error("No CPU cores specified. Provide a list of CPU cores (e.g., 0 1 2 or 0-3).")

    try:
        target_cores = parse_cpu_cores(raw_cores)
    except ValueError as e:
        parser.error(str(e))

    if not target_cores:
        parser.error("Parsed list of CPU cores is empty.")

    return input_log, target_log, target_cores, args.include_global


def main():
    input_log, target_log, target_cores, include_global = parse_args()

    if not os.path.exists(input_log):
        print(f"Error: Input log file '{input_log}' not found.", file=sys.stderr)
        sys.exit(1)

    if not os.path.isfile(input_log):
        print(f"Error: '{input_log}' is not a regular file.", file=sys.stderr)
        sys.exit(1)

    # Ensure output directory exists if specified
    out_dir = os.path.dirname(target_log)
    if out_dir and not os.path.exists(out_dir):
        os.makedirs(out_dir, exist_ok=True)

    sorted_cores = sorted(target_cores)
    cores_str = ", ".join(str(c) for c in sorted_cores)
    print(f"Filtering '{input_log}' -> '{target_log}'")
    print(f"Target CPU cores ({len(target_cores)}): [{cores_str}]")
    if include_global:
        print("Including global scheduler lifecycle events (SCHED_START, SCHED_END).")

    try:
        total, matched, event_counts = filter_log(input_log, target_log, target_cores, include_global)
    except Exception as e:
        print(f"Error processing log file: {e}", file=sys.stderr)
        sys.exit(1)

    print(f"\nDone: {matched:,} / {total:,} lines matched ({matched / total * 100:.1f}%)" if total else "\nDone: 0 lines processed.")
    if event_counts:
        print("\nFiltered events by type:")
        for ev, count in sorted(event_counts.items()):
            print(f"  {ev:<20}: {count:>8,}")


if __name__ == "__main__":
    main()
